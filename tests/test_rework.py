"""Exercise rejection, repair and downstream review on an existing episode database."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import shutil
import sqlite3
import subprocess
import sys
import tempfile
import unittest

import test_quality


class ReworkTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        self.episode = self.root / "ep"
        self.cli("init", "--topic", "검증")
        self.form = self.episode / "analysis/handoff.json"
        self.form.write_text(json.dumps(dict.fromkeys(json.loads(self.form.read_text()), "기록")))
        self.file = self.episode / "analysis/observations.md"
        self.file.write_text("초안")
        self.cli("submit", "analysis", "--by", "분석")
        self.reject = ("reject", "analysis", "--submission", "1", "--by", "검수",
                       "--owner", "분석", "--reason", "분모를 원문에서 대조")

    def cli(self, command, *args, error=None):
        res = subprocess.run([sys.executable, str(test_quality.STUDIO), "--root", str(self.root),
                              command, "ep", *args], capture_output=True, text=True)
        if error:
            self.assertNotEqual(res.returncode, 0)
            self.assertIn(error, res.stderr)
        else:
            self.assertEqual(res.returncode, 0, res.stderr)
        return res.stdout

    def test_reject_retry_fix_and_history(self):
        with sqlite3.connect(self.episode / "studio.db") as db:
            self.assertFalse(db.execute("select name from sqlite_master where name='rejections'").fetchone())
        with ThreadPoolExecutor(max_workers=3) as pool:
            list(pool.map(lambda _: self.cli(*self.reject), range(3)))
        self.assertIn("분모를 원문에서 대조", self.cli("brief", "analysis"))
        self.assertIn("수정 담당 분석", self.cli("status"))
        self.assertEqual(self.cli("history").count("반송 #1"), 1)
        self.cli("submit", "analysis", "--by", "대체", error="동일")
        data = json.loads(self.form.read_text())
        data["미확인 사항"] = "인계 문구만 교체"
        self.form.write_text(json.dumps(data))
        self.cli("submit", "analysis", "--by", "분석", error="동일")
        self.file.write_text("수정본: 분모 50개 집단")
        with ThreadPoolExecutor(max_workers=3) as pool:
            list(pool.map(lambda _: self.cli("submit", "analysis", "--by", "분석"), range(3)))
        history = self.cli("history")
        self.assertEqual(len(history.splitlines()), 3)
        self.assertIn("수정 접수 #2", history)
        self.assertNotIn("반송 #", self.cli("brief", "analysis"))
        self.cli(*self.reject, error="번호")
        self.cli("reject", "analysis", "--submission", "2", "--by", "검수",
                 "--owner", "  ", "--reason", "수정", error="담당자")
        self.file.write_text("작업 중")
        self.cli("reject", "analysis", "--submission", "2", "--by", "검수",
                 "--owner", "분석", "--reason", "수정", error="유효")

    def test_upgrade_preserves_work_and_invalidates_previous_comparison_policy(self):
        sys.path.insert(0, str(test_quality.STUDIO.parent))
        self.addCleanup(sys.path.remove, str(test_quality.STUDIO.parent))
        import studio

        decision = self.episode / "qa/decision.json"
        decision.unlink()
        self.cli("upgrade")
        self.assertEqual(json.loads(decision.read_text())["decision"], "pending")
        decision.write_text('{"decision":"editing"}')
        self.cli("upgrade")
        self.assertEqual(json.loads(decision.read_text())["decision"], "editing")
        folder = self.episode / "comparison"
        old = hashlib.sha256()
        for name in ("handoff.json", "scorecard.json"):
            old.update(name.encode() + bytes([0]))
            old.update(hashlib.sha256((folder / name).read_bytes()).digest())
        self.assertNotEqual(old.hexdigest(), studio.digest(folder, ["scorecard.json"]))

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"), "requires FFmpeg")
    def test_dependent_stage_needs_new_review(self):
        # Reuse media generated by the existing acceptance fixture without copying the DB.
        fixture = test_quality.ReleaseReviewTest()
        fixture.setUp()
        self.addCleanup(fixture.doCleanups)
        shutil.copytree(fixture.evidence, self.episode / "evidence", dirs_exist_ok=True)
        self.cli("submit", "evidence", "--by", "원본")
        self.cli(*self.reject)
        self.assertRegex(self.cli("status"), r"evidence\s+재제출 필요")
        self.cli("submit", "evidence", "--by", "원본", error="선행")
        self.file.write_text("수정본")
        self.cli("submit", "analysis", "--by", "분석")
        self.assertRegex(self.cli("status"), r"evidence\s+재제출 필요")
        self.cli("submit", "evidence", "--by", "원본")
        self.assertRegex(self.cli("status"), r"evidence\s+접수 #4")

if __name__ == "__main__":
    unittest.main()
